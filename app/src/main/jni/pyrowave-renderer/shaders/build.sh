#!/bin/sh
# Regenerates ../shaders_spv.h from the GLSL sources with the NDK's glslc.
# The SPIR-V is committed so the app build needs no shader compiler.
#
#   ANDROID_NDK=/path/to/ndk sh build.sh
#
# k_PlanarCscWarpFragSpv is planar_csc.frag built with -DFRAME_WARP (it includes frame_warp.glsl;
# Frame Warp). It is NOT in the committed shaders_spv.h, which has PYROWAVE_WARP_SPV 0: this
# script is what makes it, and defines PYROWAVE_WARP_SPV as 1, which turns Frame Warp drawing on in
# pyrowave_renderer.cpp. No shader compiler was at hand when Frame Warp was written, and the warp
# SPIR-V was deliberately not assembled by hand: run this script with the NDK, check the diff of
# shaders_spv.h (the other three arrays should not change) and commit it.
set -e
cd "$(dirname "$0")"

GLSLC="$(ls "$ANDROID_NDK"/shader-tools/*/glslc* | head -n 1)"
OUT=../shaders_spv.h

emit() {
    # $1: source file, $2: C array name, $3...: extra glslc options
    src="$1"
    name="$2"
    shift 2
    "$GLSLC" -O --target-env=vulkan1.1 -mfmt=num "$@" -o "$src.inc" "$src"
    {
        echo "static const uint32_t $name[] = {"
        cat "$src.inc"
        echo "};"
        echo
    } >> "$OUT"
    rm "$src.inc"
}

{
    echo "// Generated by shaders/build.sh from fullscreen.vert, planar_csc.frag (also with -DFRAME_WARP) and keep_busy.comp. Do not edit."
    echo "#pragma once"
    echo
    echo "#include <stdint.h>"
    echo
    echo "// 1 when k_PlanarCscWarpFragSpv is below: Frame Warp can be drawn"
    echo "#define PYROWAVE_WARP_SPV 1"
    echo
} > "$OUT"

emit fullscreen.vert k_FullscreenVertSpv
emit planar_csc.frag k_PlanarCscFragSpv
emit planar_csc.frag k_PlanarCscWarpFragSpv -DFRAME_WARP
emit keep_busy.comp k_KeepBusyCompSpv
